#!/usr/bin/env python3
"""Compile src/hle/guest_libc.c to x86-64 and embed it as a C++ byte array.

Writes include/ps4/guest_libc_blob.hpp with the .text bytes and the offset of
each exported guest_* function. The code must not need relocations; the
script refuses to emit a blob whose object file has any.

usage: python3 scripts/gen_guest_libc.py
"""
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src/hle/guest_libc.c"
OUT = ROOT / "include/ps4/guest_libc_blob.hpp"

FLAGS = [
    "clang", "-target", "x86_64-unknown-freebsd", "-O2", "-c",
    "-ffreestanding", "-fno-builtin", "-fno-stack-protector", "-fpie",
    "-fno-asynchronous-unwind-tables", "-fno-unwind-tables",
    "-mno-sse", "-mno-mmx", "-mno-avx", "-mno-red-zone",
]


def sections(elf):
    shoff, = struct.unpack_from("<Q", elf, 0x28)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", elf, 0x3A)
    hdrs = [struct.unpack_from("<IIQQQQIIQQ", elf, shoff + i * shentsize) for i in range(shnum)]
    strtab_off = hdrs[shstrndx][4]

    def name(off):
        end = elf.index(b"\0", strtab_off + off)
        return elf[strtab_off + off:end].decode()

    return [(name(h[0]), h) for h in hdrs]


def main():
    with tempfile.TemporaryDirectory() as tmp:
        obj = Path(tmp) / "guest_libc.o"
        subprocess.run(FLAGS + [str(SRC), "-o", str(obj)], check=True)
        elf = obj.read_bytes()

    secs = sections(elf)
    relocs = [n for n, h in secs if h[1] in (4, 9) and h[5] > 0]  # SHT_RELA / SHT_REL
    if relocs:
        sys.exit(f"guest_libc.o has relocations {relocs}; the blob must be position independent")
    text_idx = next(i for i, (n, _) in enumerate(secs) if n == ".text")
    text = secs[text_idx][1]
    code = elf[text[4]:text[4] + text[5]]

    symtab = next(h for n, h in secs if n == ".symtab")
    strtab = secs[symtab[6]][1]
    entries = {}
    for i in range(symtab[5] // 24):
        st_name, st_info, _, st_shndx, st_value, _ = struct.unpack_from("<IBBHQQ", elf, symtab[4] + i * 24)
        end = elf.index(b"\0", strtab[4] + st_name)
        nm = elf[strtab[4] + st_name:end].decode()
        if nm.startswith("guest_") and st_shndx == text_idx and (st_info & 0xF) == 2:
            entries[nm] = st_value

    lines = [
        "// Generated by scripts/gen_guest_libc.py from src/hle/guest_libc.c. Do not edit.",
        "#pragma once",
        "",
        '#include "ps4/common.hpp"',
        "",
        "namespace ps4::guest_libc {",
        "",
    ]
    for nm, off in sorted(entries.items(), key=lambda kv: kv[1]):
        lines.append(f"inline constexpr usize k_{nm[len('guest_'):]}_offset = 0x{off:x};")
    lines += ["", f"inline constexpr u8 kCode[{len(code)}] = {{"]
    for i in range(0, len(code), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in code[i:i + 16]) + ",")
    lines += ["};", "", "} // namespace ps4::guest_libc", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(code)} bytes, entries {entries}")


if __name__ == "__main__":
    main()
